import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { K386_BOOT_URL } from '../src/bundled-k386';
import { fatReadFile, openDiskImage } from '../src/api/fat';

const manifest = JSON.parse(readFileSync('public/k386/manifest.json', 'utf8'));
describe('optional experimental K386 disk', () => {
  it('offers a separate explicit boot choice only after generation', () => {
    expect(K386_BOOT_URL).toBe(manifest.enabled ? `./?fd1=./k386/${manifest.image}&run=1&mem=16` : undefined);
  });
  it('keeps generated bytes and the pinned native source verifiable', () => {
    if (!manifest.enabled) return;
    const image = readFileSync(`public/k386/${manifest.image}`);
    expect(createHash('sha256').update(image).digest('hex')).toBe(manifest.sha256);
    expect(manifest.dos_files_read_only).toBe(true);
    expect(manifest.extended_memory_mb).toBe(16);
    expect(manifest.source_commit).toMatch(/^[a-f0-9]{40}$/);
    expect(manifest.files.map((file: {name: string}) => file.name)).toEqual(expect.arrayContaining([
      'K386.EXE', 'K386CPU.COM', 'K386TEST.COM', 'KDESK.EXE', 'COUNTER.EXE', 'ECHO.EXE', 'KFILE.EXE', 'PORT.EXE', 'DF.EXE', 'FPU.EXE',
      'KSH.EXE', 'KHELLO.EXE', 'BADAPP.EXE', 'MZTEST.EXE', 'FLAGS.EXE', 'DTA.EXE', 'KEYCHK.EXE', 'TIMER.EXE', 'MEMORY.EXE', 'PROCESS.EXE', 'BADTIMER.EXE', 'ROMWRITE.EXE', 'FDXMS286.SYS', 'KRESCHK.COM', 'INTWAIT.EXE', 'CASE.EXE', 'XMEM.EXE', 'XCHILD.EXE',
    ]));
  });
  it('packages the V86 apps as tagged MZ executables with valid relocations', () => {
    if (!manifest.enabled) return;
    const disk = openDiskImage(readFileSync(`public/k386/${manifest.image}`), manifest.image);
    const names=manifest.files.map((file: {name: string})=>file.name);
    for(const stem of 'KSH KHELLO COUNTER ECHO FAULT KFILE PORT DF FPU FLAGS DTA KEYCHK TIMER MEMORY PROCESS BADTIMER ROMWRITE INTWAIT CASE XMEM XCHILD'.split(' ')) {
      expect(names).not.toContain(stem+'.COM');
      const exe=fatReadFile(disk,stem+'.EXE');
      const word=(at:number)=>exe[at]|exe[at+1]<<8;
      expect(word(0)).toBe(0x5a4d);
      expect(new TextDecoder().decode(exe.slice(28,36))).toBe('K386APP1');
      expect(word(36)).toBe(0x0100);expect(word(38)).toBe(1);
      expect(word(24)).toBe(72);expect(word(6)).toBeGreaterThan(0);
      expect(word(24)+4*word(6)).toBeLessThanOrEqual(word(8)*16);
      expect((word(4)-1)*512+(word(2)||512)).toBe(exe.length);
      const moduleSize=exe.length-word(8)*16;
      expect(word(22)*16+word(20)).toBeLessThan(moduleSize);
      expect((Math.ceil(moduleSize/16)+word(10))*16).toBe(0x10000);
      for(let i=0;i<word(6);i++) {
        const at=word(24)+i*4;
        expect(word(at)+word(at+2)*16+2).toBeLessThanOrEqual(moduleSize);
      }
    }
  });
  it('boots XMS without an existing V86 owner and preserves kernel provenance', () => {
    if (!manifest.enabled) return;
    const disk = openDiskImage(readFileSync(`public/k386/${manifest.image}`), manifest.image);
    const normal = JSON.parse(readFileSync('public/msdos4/manifest.json', 'utf8'));
    const baseline = openDiskImage(readFileSync(`public/msdos4/${normal.image}`), normal.image);
    const names=manifest.files.map((file: {name: string})=>file.name);
    expect(names).not.toContain('KDESK.COM');
    expect(names).not.toContain('K386.COM');
    for(const name of ['KDESK.EXE','K386.EXE']) {
      const exe=fatReadFile(disk,name);
      const word=(at:number)=>exe[at]|exe[at+1]<<8;
      expect(word(0)).toBe(0x5a4d);
      expect((word(4)-1)*512+(word(2)||512)).toBe(exe.length);
      expect(word(10)).toBe(word(12));
      expect(word(6)).toBe(name==='KDESK.EXE'?1:0);
      if(name==='KDESK.EXE')expect(word(14)).toBeGreaterThan(word(22));
    }
    const config = new TextDecoder().decode(fatReadFile(disk, 'CONFIG.SYS'));
    expect(config).toContain('DEVICE=FDXMS286.SYS');
    expect(config).not.toContain('DEVICE=EMM386');
    expect(new TextDecoder().decode(fatReadFile(disk, 'AUTOEXEC.BAT'))).toContain('K386.EXE\r\nKDESK.EXE\r\n');
    for (const name of ['IO.SYS', 'MSDOS.SYS', 'COMMAND.COM', 'FDXMS286.SYS']) {
      expect(fatReadFile(disk, name)).toEqual(fatReadFile(baseline, name));
    }
    const pin = readFileSync('scripts/prepare-msdos4-cpanel-ci.sh', 'utf8').match(/source_commit=([a-f0-9]{40})/);
    expect(manifest.source_commit).toBe(pin?.[1]);
    expect(normal.sources.window.commit).toBe(manifest.source_commit);
    expect(manifest.base_image_sha256).toBe(normal.sha256);
  });
});
