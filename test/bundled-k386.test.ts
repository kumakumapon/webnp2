import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { K386_BOOT_URL } from '../src/bundled-k386';

const manifest = JSON.parse(readFileSync('public/k386/manifest.json', 'utf8'));
describe('optional experimental K386 disk', () => {
  it('offers a separate explicit boot choice only after generation', () => {
    expect(K386_BOOT_URL).toBe(manifest.enabled ? `./?fd1=./k386/${manifest.image}&run=1` : undefined);
  });
  it('keeps generated bytes and the pinned native source verifiable', () => {
    if (!manifest.enabled) return;
    const image = readFileSync(`public/k386/${manifest.image}`);
    expect(createHash('sha256').update(image).digest('hex')).toBe(manifest.sha256);
    expect(manifest.dos_files_read_only).toBe(true);
    expect(manifest.source_commit).toMatch(/^[a-f0-9]{40}$/);
    expect(manifest.files.map((file: {name: string}) => file.name)).toEqual(expect.arrayContaining([
      'K386.COM', 'K386CPU.COM', 'K386TEST.COM', 'KDESK.COM', 'COUNTER.COM', 'ECHO.COM', 'KFILE.COM', 'PORT.COM', 'DF.COM', 'FPU.COM',
      'KSH.COM', 'MZTEST.EXE', 'FLAGS.COM', 'DTA.COM', 'KEYCHK.COM',
    ]));
  });
});
